import { useState, type ReactNode } from 'react';
import { BackIcon, CloseIcon, MenuIcon, ArrowRight } from './Icons';
import { navigate } from '../lib/hooks';

const LINKS = [
  { to: 'home', label: 'Race weekend' },
  { to: 'live', label: 'Live tracker' },
  { to: 'drivers', label: 'Drivers' },
];

export function Topbar({ title, back, current }: { title: ReactNode; back?: string; current: string }) {
  const [open, setOpen] = useState(false);
  return (
    <>
      <header className="topbar">
        {back ? (
          <button className="iconbtn" aria-label="Back" onClick={() => navigate(back)}>
            <BackIcon />
          </button>
        ) : (
          <a className="brand__mark" href="#home" aria-label="Pitwall home">
            <svg width="24" height="24" viewBox="0 0 32 32">
              <path d="M4 24 14 8h14L18 24Z" fill="#fff" />
            </svg>
          </a>
        )}
        <div className="topbar__title">{title}</div>
        <button className="iconbtn" aria-label="Open menu" onClick={() => setOpen(true)}>
          <MenuIcon />
        </button>
      </header>
      {open && (
        <>
          <div className="drawer-backdrop" onClick={() => setOpen(false)} />
          <nav className="drawer" aria-label="Main">
            <div className="drawer__head">
              <span className="brand">
                <span className="brand__mark" style={{ width: 34, height: 34 }}>
                  <svg width="18" height="18" viewBox="0 0 32 32">
                    <path d="M4 24 14 8h14L18 24Z" fill="#fff" />
                  </svg>
                </span>
                Pitwall
              </span>
              <button className="iconbtn" aria-label="Close menu" onClick={() => setOpen(false)}>
                <CloseIcon />
              </button>
            </div>
            {LINKS.map((l) => (
              <a key={l.to} href={'#' + l.to} className={current === l.to ? 'active' : ''} onClick={() => setOpen(false)}>
                {l.label}
                <ArrowRight />
              </a>
            ))}
            <p className="drawer__foot">
              Live timing is simulated in your browser — positions, gaps, pit stops and incidents are generated by a race model. Driver
              career data is compiled through the 2025 season.
            </p>
          </nav>
        </>
      )}
    </>
  );
}
